"""Train the TSP model and report the beam-decoded tour ratio.

    python experiments/run_tsp.py --n-cities 5 --samples 500
    python experiments/run_tsp.py --train-split data/tsp10_train.pkl --test-split data/tsp10_test.pkl

Benchmark splits are pickle files with ``coordinates``, ``optimal_tours``, and
``optimal_lengths`` (generated by experiments/generate_tsp.py). Without a split,
random instances with exact optimal tours are used.
"""
import argparse

import numpy as np
import torch

from mp_qgnns.data_io.tsp import load_split, random_instances, tour_length
from mp_qgnns.models.tsp import TSPQGNN
from mp_qgnns.training.tsp import tour_ratio, train

torch.set_default_dtype(torch.float64)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-cities", type=int, default=5)
    ap.add_argument("--samples", type=int, default=500)
    ap.add_argument("--train-split", default=None)
    ap.add_argument("--test-split", default=None)
    ap.add_argument("--epochs", type=int, default=400)
    ap.add_argument("--lr", type=float, default=3e-3)
    ap.add_argument("--beam-width", type=int, default=5)
    args = ap.parse_args()

    if args.train_split:
        tr_coords, _, tr_heat = load_split(args.train_split)
        te_coords, te_tours, _ = load_split(args.test_split or args.train_split)
        n = tr_coords.shape[1]
    else:
        n = args.n_cities
        tr_coords, _, tr_heat = random_instances(n, args.samples, seed=0)
        te_coords, te_tours, _ = random_instances(n, args.samples // 2, seed=1)

    opt = np.array([tour_length(te_coords[i].numpy(), te_tours[i].numpy())
                    for i in range(len(te_coords))])
    model = TSPQGNN(n)
    print(f"n={n}  before training: tour ratio {tour_ratio(model, te_coords, opt, args.beam_width):.4f}")
    train(model, tr_coords, tr_heat, epochs=args.epochs, lr=args.lr)
    print(f"n={n}  after  training: tour ratio {tour_ratio(model, te_coords, opt, args.beam_width):.4f}")


if __name__ == "__main__":
    main()
